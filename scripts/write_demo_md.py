"""Write DEMO.md: start-up commands, the 5-minute script, and validated menus.

The menus (edit pairs, invented names, companies) and every number are read
from results/, so DEMO.md can be regenerated after any re-run.

    uv run python scripts/write_demo_md.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from terra import RESULTS, ROOT  # noqa: E402


def load(name):
    p = RESULTS / name
    return json.loads(p.read_text()) if p.exists() else None


def main() -> int:
    # Use the menu and edit evaluation for the patch method the server will use
    # (same rule as terra/server.py: all-token if adopted and its menu exists).
    mt = load("multitoken_eval.json") or {}
    all_tok = bool(mt.get("adopt")) and (RESULTS / "pair_menu_alltoken.json").exists()
    menu_name = "pair_menu_alltoken.json" if all_tok else "pair_menu.json"
    eval_name = "edit_eval_fresh_alltoken.json" if all_tok and (RESULTS / "edit_eval_fresh_alltoken.json").exists() else "edit_eval.json"
    pm, fi, _co, st, ev, pf, dc = (load(n) for n in (menu_name, "fictional.json", "companies.json",
                                                    "steer_eval.json", eval_name, "probe_final.json",
                                                    "demo_check.json"))
    L = ["# DEMO", "", "Generated by `scripts/write_demo_md.py` from `results/`. Rehearse from this page.", ""]
    L += ["## Start-up (Wi-Fi can be off)", "", "```bash",
          'cd "<project folder>"',
          "uv run uvicorn terra.server:app --port 8000",
          "# wait for: [server] ready ... (10 to 30 s), then open http://localhost:8000",
          "```", "",
          "- Close every other program that has the model loaded (batch scripts, notebooks). Two copies do not fit in memory.",
          "- Close games and other GPU-heavy apps: a game running during the build made every model call several times slower.",
          "- Use Chrome or Safari, full screen, at least 1400 px wide.",
          "- First edit or locate after start-up may take a second or two longer (MPS warm-up).",
          "- Health check: http://localhost:8000/api/health",
          "- Full automated check: stop the server, then `uv run python scripts/demo_check.py` (starts its own server on port 8765).", ""]
    if dc:
        L += [f"Last demo check: {dc['n_pass']}/{dc['n_checks']} checks passed at {dc['time']} (`results/demo_check.json`).", ""]

    L += ["## The 5-minute script", ""]
    probe_line = ""
    if pf:
        probe_line = (f" Say: \"For places the probe never saw, the median error is {pf['heldout']['random']['median_km']:,.0f} km; "
                      f"if we hide whole countries from it, {pf['heldout']['blocked_country']['median_km']:,.0f} km.\"")
    rewrite_line = ""
    rw = load("rewrite_eval.json")
    if rw:
        sw = rw["summary"]["swap"]
        rewrite_line = (f" Say: \"Over {sw['n_worlds']} random three-move worlds, {sw['city_pass_rate']:.0%} of moved cities change all their "
                        f"answers, and {sw['pair_questions']['all']['after_consistent_rate']:.0%} of answers about two moved cities fit the rewritten world.\"")
    edit_line = ""
    if ev:
        e, c = ev["sets"]["cross"]["edit"], ev["sets"]["cross"]["control"]
        edit_line = (f" Say: \"On {e['n_pairs']} fresh random city pairs across hemispheres, the edit succeeds {e['pass_rate']:.0%} "
                     f"of the time; a random push of the same size succeeds {c['pass_rate']:.0%}.\" (`results/{eval_name}`)")
    L += [
        "1. **Hook (15 s).** \"Every language model carries a map of the Earth that nobody drew. We pulled it out, and then we learned to edit it.\"",
        "2. **The map (45 s).** Map tab. Rotate the globe; the dots are where the model believes places are, coloured by true continent, lines go to the true position. Click a dot." + probe_line,
        "3. **New worlds (60 s).** New worlds tab. Hand the keyboard to the judge, or click a suggestion chip. Read out the nearest real city.",
        "4. **The edit (90 s).** Edit tab. Drag the Paris marker onto Sydney (or pick Paris -> Sydney and press Move). The ripple table fills: before, after, random control; the landmark row shows the Eiffel Tower becoming the Sydney Opera House. Press \"Ask before and after\" on the Christmas packing question (the edited answer adds sunscreen and a hat), or let the judge type a question that mentions Paris. Then tick \"move: X stays X\", pick Berlin -> Cape Town and press Move: Germany, euro, German and the Brandenburg Gate stay, but the model now says Southern Hemisphere and winter in July.",
        "5. **Rewrite the world (45 s).** Rewrite tab. Click a suggested world (or drag up to three cities onto new places, then press Rewrite). Every city's answers change, and the questions about two moved cities (\"Are Paris and Tokyo in the same hemisphere?\") answer for the rewritten world. Then press \"Ask before and after\" on the packing question that mentions all three cities." + rewrite_line,
        "6. **Rigour (30 s).** Rigour tab: held-out error, edit success against the control, invented-name chance level. Prior work: Gurnee & Tegmark 2023; Chen et al. 2023." + edit_line,
        "7. **Close (15 s).**", ""]

    if pm:
        L += ["## Validated edit pairs", "",
              f"{pm['n_validated']} of {pm['n_pairs']} ordered pairs pass (rule: {pm['rule']}; patch method: "
              f"{'every name token' if pm.get('method') == 'all' else 'last name token'}, `results/{menu_name}`). "
              "All are cached, so they answer instantly.", ""]
        by_src = {}
        for p in pm["pairs"]:
            by_src.setdefault(p["source"], []).append(p["target"])
        L += ["| Source | Validated targets |", "|---|---|"]
        for s in sorted(by_src):
            L.append(f"| {s} | {', '.join(sorted(by_src[s]))} |")
        L.append("")
        if pm.get("free_answers"):
            L += ["### Precomputed free answers (headline pairs)", ""]
            for a in pm["free_answers"][:8]:
                L += [f"- **{a['source']} -> {a['target']}.** Before: \"{a['before']}\" After: \"{a['after']}\""]
            L.append("")
    if fi:
        L += ["## Invented names", "",
              f"{fi['n_coherent']} of {fi['n_scored']} scored names land in the region their sound suggests "
              f"(chance level {fi['chance_rate_mean']:.0%}). Suggested names (these are the chips in the UI):", ""]
        good = [r for r in fi["results"] if r["coherent"]]
        L += ["| Name | Lands near | Expected |", "|---|---|---|"]
        for r in good:
            L.append(f"| {r['name']} | {r['nearest']['name']}, {r['nearest']['country']} | {r['expected_group']} |")
        L += ["", "Names that do *not* land coherently (avoid on stage unless making that point): " +
              ", ".join(f"{r['name']} ({r['nearest']['country']})" for r in fi["results"] if r["coherent"] is False), ""]
    rm = load("rewrite_menu.json")
    if rm:
        L += ["## Suggested worlds (Rewrite tab)", "",
              "Precomputed, so they answer instantly. Any other combination of up to three moves runs live (about 10 to 15 s).", ""]
        for w in rm["worlds"]:
            r = w["results"]["swap"]
            moves = ", ".join(f"{m['source']} -> {m['target']}" for m in w["moves"])
            n_pass = sum(bool(c.get("passes")) for c in r["cities"])
            sc = [p for p in r["pairs"] if p["key_after"] is not None and p["before_correct"]]
            ok = sum(p["after_correct"] for p in sc)
            L += [f"- **{w['name']}** ({moves}): {n_pass}/{len(r['cities'])} cities change all their answers; "
                  f"{ok}/{len(sc)} scoreable pair answers fit the rewritten world.",
                  f"  - Free question after: \"{r['free']['after']}\""]
        L.append("")
    if st:
        L += ["## Move, don't swap (tier 2)", ""]
        if st["keep"]:
            ch = st["chosen"]
            L += [f"Available as the \"move: X stays X\" radio button in the Edit tab (probe-direction steering, layers "
                  f"{ch['band'][0]}-{ch['band'][1]}, scale {ch['scale']:g}). On the gate pairs it moved the hemisphere or season "
                  f"answer with the landmark kept on {st['best']['n_moved_and_kept']}/{len(st['pairs'])}."]
            sh = load("steer_heldout.json")
            if sh:
                r = sh["rates"]["steer"]
                L += [f"On {sh['n_pairs']} fresh pairs: location moved {r['moved']:.0%}, identity kept {r['identity_kept']:.0%}, "
                      f"both {r['moved_and_kept']:.0%} (control: moved {sh['rates']['control']['moved']:.0%}). "
                      "Say \"often\", not \"always\"."]
            best = [x for x in st["sweep"] if x.get("method") == "steer" and x["band"] == ch["band"] and x["scale"] == ch["scale"]][0]
            ref = st["reference"]
            good = [p for p in best["pairs"] if p["landmark_kept"] and p["moved"] and p["n_flipped"] >= 2
                    and p["answers"]["country"] == ref[f"{p['source']}->{p['target']}"]["before"][0]]
            if good:
                L += ["", "Best pairs to show in move mode (in the gate run: hemisphere and season moved, country and landmark kept):", ""]
                for p in good:
                    L.append(f"- {p['source']} -> {p['target']}: {p['answers']['country']}, {p['answers']['hemisphere']}, "
                             f"July {p['answers']['season']}, landmark {p['landmark']}")
            L.append("")
        else:
            L += [f"Not in the demo: the best setting moved the hemisphere or season answer while keeping the landmark on only "
                  f"{st['best']['n_moved_and_kept']}/{len(st['pairs'])} gate pairs (rule needs half). Say so if asked.", ""]
    L += ["## If something goes wrong", "",
          "- Globe blank: hard-refresh the page; check the server terminal for errors.",
          "- An edit seems slow: the first live (uncached) edit takes a few seconds; menu pairs are instant.",
          "- Server will not start: another process holds the model. Quit it, or restart the Mac's terminal session.", ""]
    (ROOT / "DEMO.md").write_text("\n".join(L))
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    sys.exit(main())
